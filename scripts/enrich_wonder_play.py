def apply():
    done = 0
    for slug, (html, faqs) in E.items():
        p = os.path.join(ROOT, 'sims', slug, 'index.html')
        if not os.path.exists(p):
            print('skip (missing):', slug); continue
        s = io.open(p, encoding='utf-8').read()
        if MARK in s:
            continue
        anchor = '<h2>よくある質問</h2>'
        if anchor not in s:
            print('skip (no FAQ anchor):', slug); continue
        s = s.replace(anchor, MARK + '\n' + html.strip() + '\n    ' + anchor, 1)
        # dl に追記
        extra = ''.join('<dt>%s</dt><dd>%s</dd>' % (q, a) for q, a in faqs)
        i = s.index(anchor)
        j = s.index('</dl>', i)
        s = s[:j] + extra + s[j:]
        # FAQPage LD に追記
        m = re.search(r'<script type="application/ld\+json">(\{[^<]*"FAQPage"[^<]*\})</script>', s)
        if m:
            ld = json.loads(m.group(1))
            ld['mainEntity'] += [{"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": re.sub(r'<[^>]+>', '', a)}} for q, a in faqs]
            s = s[:m.start(1)] + json.dumps(ld, ensure_ascii=False) + s[m.end(1):]
        else:
            print('warn: no FAQPage LD:', slug)
        io.open(p, 'w', encoding='utf-8').write(s)
        done += 1
        print('enriched:', slug)
    print('done. %d pages enriched (%d defined).' % (done, len(E)))

if __name__ == '__main__':
    apply()
