NOTE = '※金額は一般的な目安です。地域・時期・条件で実際の費用は変わります。ご自身の数字を入れて概算にお使いください。'

def RES(label, unit='円'):
    return (f'''      <div class="label">{label}</div>
      <div class="big"><span id="big">0</span><span class="unit">{unit}</span></div>
      <div class="sub" id="sub">内訳を入力してください</div>
      <div id="bd" style="margin-top:14px;text-align:left;"></div>''')

def N(key, label, hint, default):        return ('N', key, label, hint, default)
def Q(pk, pl, ph, pd, qk, qh, qd, line):  return ('Q', pk, pl, ph, pd, qk, qh, qd, line)
def S(key, label, opts, line):            return ('S', key, label, opts, line)

def stack(id, emoji, title, desc, ogtitle, ogdesc, h1, lead, qhead, items,
          totlabel, sharetag, art_h2, art_p, faqs, note='', unit='円'):
    rows = [f'    <h2>{emoji} {qhead}</h2>']
    for it in items:
        t = it[0]
        if t == 'N':
            _, k, lab, hint, dv = it
            h = f' <span class="hint">{hint}</span>' if hint else ''
            rows.append(f'    <div class="field"><label>{lab}{h}</label><input type="number" id="{k}" value="{dv}" min="0" inputmode="numeric"></div>')
        elif t == 'Q':
            _, pk, pl, ph, pd, qk, qh, qd, line = it
            ph2 = f' <span class="hint">{ph}</span>' if ph else ''
            qh2 = f' <span class="hint">{qh}</span>' if qh else ''
            rows.append(f'''    <div class="row"><div class="field"><label>{pl}{ph2}</label><input type="number" id="{pk}" value="{pd}" min="0" inputmode="numeric"></div>
    <div class="field"><label>{line}の数{qh2}</label><input type="number" id="{qk}" value="{qd}" min="0" inputmode="numeric"></div></div>''')
        elif t == 'S':
            _, k, lab, opts, line = it
            os_ = ''.join(f'<option value="{v}"{" selected" if i==0 else ""}>{txt}</option>' for i,(txt,v) in enumerate(opts))
            rows.append(f'    <div class="field"><label>{lab}</label><select id="{k}">{os_}</select></div>')
    rows.append(f'    <button class="btn btn-primary" id="calcBtn">合計コストを計算</button>')
    inputs = '\n'.join(rows)

    lines = []
    for it in items:
        t = it[0]
        if t == 'N':
            _, k, lab, hint, dv = it
            lines.append(f"L.push([{json.dumps(lab, ensure_ascii=False)}, Math.max(0,+$('{k}').value||0)]);")
        elif t == 'Q':
            _, pk, pl, ph, pd, qk, qh, qd, line = it
            lines.append(f"L.push([{json.dumps(line, ensure_ascii=False)}, Math.max(0,+$('{pk}').value||0)*Math.max(0,+$('{qk}').value||0)]);")
        elif t == 'S':
            _, k, lab, opts, line = it
            lines.append(f"L.push([{json.dumps(line, ensure_ascii=False)}, Math.max(0,+$('{k}').value||0)]);")
    js = ('  function calc(){const L=[];\n    ' + '\n    '.join(lines) + '\n'
          + "    const tot=L.reduce((a,x)=>a+x[1],0), cnt=L.filter(x=>x[1]>0).length;\n"
          + "    $('bd').innerHTML=BD(L)+`<div style=\"display:flex;justify-content:space-between;gap:12px;padding:12px 2px 2px;font-size:15px;\"><span style=\"font-weight:800\">合計</span><b>${yen(tot)}</b></div>`;\n"
          + f"    $('sub').textContent=`{totlabel}・内訳${{cnt}}項目`;\n"
          + f"    SHARE=`{title.split('｜')[0]}を計算したら約${{yen(tot)}}でした{sharetag} #シミュラボ`;\n"
          + "    show();anim(tot);}\n" + ANIM)

    article = (f'''    <div class="note"><strong>{art_h2}</strong><br>{note or NOTE}</div>
    <h2>{art_h2}</h2>
    <p>{art_p}</p>
    <h2>よくある質問</h2>''' + faq(faqs))
    add(id=id, emoji=emoji, title=title, desc=desc, ogtitle=ogtitle, ogdesc=ogdesc,
        h1=h1, lead=lead, inputs=inputs, result=RES(totlabel, unit), article=article, js=js)


